/// 新增与编辑模板共用语法文案，展示行为由共享帮助入口负责。
abstract final class TemplatePromptSyntaxHelp {
  static String get message =>
      '${_exampleLines.join('\n')}\n\n${_limitations.join('\n\n')}';
  static const _exampleLines = <String>[
    '{{主角名}}',
    '{{章节数:number}}',
    '{{人称:select|一|二|三}}',
    '{{#if 人称 == "一"}}',
    '使用“我”的口吻，主角是{{主角名}}。',
    '{{else if 人称 == "二"}}',
    '使用“你”的口吻。',
    '{{else}}',
    '使用第三人称。',
    '{{/if}}',
  ];

  static const _limitations = <String>[
    '文本与单选变量支持 == 和 !=；数字变量还支持 >、>=、<、<=。',
    '字符串字面量需用双引号，整数不用引号。',
    '单选变量用 | 分隔选项，条件分支内可以使用普通变量。',
    '控制标签可与正文同行或独占一行；独占一行的控制标签会整行移除，不留空白行。',
    '{{正文}} 必须放在条件块之外；模板未写 {{正文}} 时，正文会插入在模板上方。',
    '{{正文}} 不能作为条件变量引用。',
    '比较运算符与变量名之间需要空白分隔（如 人称== "一" 会被拒绝）。',
    '第一版不支持嵌套条件、组合条件、模板引用与渲染预览，不支持在单选选项中使用 |，也不支持把 {{ 转义为字面文本。',
  ];
}
